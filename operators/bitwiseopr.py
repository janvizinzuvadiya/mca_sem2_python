a=6 # 0110
b=3 # 0011

# 2-> 0010 ,7-> 0111 ,5-> 0101 , 
# for 2's compliment add 1 at the end 

#  Bitwise AND : &
print(a&b)

#  Bitwise OR : |
print(a|b)

#  Bitwise XOR : ^
print(a^b)

#  Bitwise NOT : ~
print(~b)

# Bitwise left shift : <<
print(a>>b)

# Bitwise right shift : >>
print(a<<b)
